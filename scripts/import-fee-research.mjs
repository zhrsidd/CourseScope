#!/usr/bin/env node
/**
 * Converts the raw fee research (data/research/fees-2027/<university>.json —
 * one file per university, every entry quoted from an official page) into the
 * bundled data module src/data/tuition-fees.2027.ts.
 *
 *   node scripts/import-fee-research.mjs
 *
 * What it does, and deliberately does not do:
 *   · copies fields as recorded — it never fills a gap or derives a figure;
 *   · keeps the researcher's note only where the student needs an explanation
 *     (awaiting-publication and unknown rows). Published rows carry their
 *     year evidence and source instead; the full notes stay in the research
 *     files, which are the audit trail;
 *   · strips cache-busting query strings (`?v=2`) used while fetching, so the
 *     source link is the page itself;
 *   · records courses with nothing established in a separate gaps list, so
 *     "not researched" and "researched, not published" stay distinct.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const RESEARCH_DIR = 'data/research/fees-2027';
const OUT = 'src/data/tuition-fees.2027.ts';
const CACHE_BUST_PARAMS = ['v', 'cs', 'nocache', 'cb'];

function cleanUrl(url) {
  if (!url) return null;
  const u = new URL(url);
  for (const p of CACHE_BUST_PARAMS) u.searchParams.delete(p);
  return u.toString();
}

const str = (v) => (typeof v === 'string' && v.trim() ? v.trim() : null);

const fees = [];
const gaps = [];
for (const file of readdirSync(RESEARCH_DIR).filter((f) => f.endsWith('.json')).sort()) {
  const doc = JSON.parse(readFileSync(join(RESEARCH_DIR, file), 'utf8'));
  for (const c of doc.courses) {
    const feeYear = c.id.split('--')[1];
    if (c.fees.length === 0) {
      gaps.push({ courseId: c.id, universityId: doc.universityId, feeYear, reason: str(c.unresolved) });
    }
    for (const f of c.fees) {
      fees.push({
        courseId: c.id,
        universityId: doc.universityId,
        feeYear,
        category: f.category.trim(),
        categoryKind: f.categoryKind,
        status: f.status,
        amount: f.amount ?? null,
        indicativeAmount: f.indicativeAmount ?? null,
        currency: f.currency ?? 'GBP',
        basis: f.basis,
        basisNote: str(f.basisNote),
        scope: f.scope,
        scopeNote: str(f.scopeNote),
        yearEvidence: str(f.yearEvidence),
        sourceUrl: cleanUrl(f.sourceUrl),
        sourceTitle: str(f.sourceTitle),
        lastVerified: doc.checkedOn,
        note: f.status === 'published' ? null : str(f.note),
      });
    }
  }
}

const header = `/**
 * GENERATED by scripts/import-fee-research.mjs from data/research/fees-2027/.
 * Do not edit by hand: correct the research file and re-run the script.
 *
 * Official 2027-entry tuition fees, one row per published category per course.
 * No 2028 rows exist: no university in the catalogue had published 2028-entry
 * fees when this was researched, and 2027 figures are never carried forward.
 */
import type { TuitionFee } from '@/types';

/** A course whose fees could not be established, with the reason. */
export interface TuitionFeeGap {
  courseId: string;
  universityId: string;
  feeYear: string;
  reason: string | null;
}
`;

/*
 * Compact encoding. The same year evidence, source titles and explanations
 * repeat across dozens of courses, so each distinct string is stored once and
 * rows refer to it by index. This keeps ~930 KB of raw rows to a fraction of
 * that in the bundle. Decoding is exact and runs once at module load; the
 * assertion suite checks every decoded row against the research files.
 */
const FIELDS = Object.keys(fees[0]);
const NUMERIC = new Set(['amount', 'indicativeAmount']);
const table = [];
const index = new Map();
const ref = (s) => {
  if (s === null) return null;
  if (!index.has(s)) {
    index.set(s, table.length);
    table.push(s);
  }
  return index.get(s);
};
const rows = fees.map((f) => FIELDS.map((k) => (NUMERIC.has(k) ? f[k] : ref(f[k]))));

writeFileSync(
  OUT,
  `${header}
const FIELDS = ${JSON.stringify(FIELDS)} as const;
const NUMERIC: ReadonlySet<string> = new Set(${JSON.stringify([...NUMERIC])});
const STRINGS: string[] = ${JSON.stringify(table)};
const ROWS: (number | null)[][] = ${JSON.stringify(rows)};

export const TUITION_FEES_2027: TuitionFee[] = ROWS.map((row) => {
  const out: Record<string, unknown> = {};
  FIELDS.forEach((field, i) => {
    const v = row[i];
    out[field] = v === null ? null : NUMERIC.has(field) ? v : STRINGS[v];
  });
  return out as unknown as TuitionFee;
});

export const TUITION_FEE_GAPS_2027: TuitionFeeGap[] = ${JSON.stringify(gaps, null, 1)};
`,
);
console.log(`${fees.length} fee rows, ${gaps.length} courses with no fee established → ${OUT}`);
